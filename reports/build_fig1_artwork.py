OP_BOTTOM, IND_TOP, LANE_BOTTOM = 66.6, 68.8, 108.6   # mm
LW_RULE, LW_LINE, LW_ARROW, LW_GENE = 0.5 * PT, 0.5 * PT, 0.6 * PT, 0.4 * PT


class Svg:
    def __init__(self):
        self.out: list[str] = []

    def add(self, s: str):
        self.out.append(s)

    def group(self, gid: str):
        self.add(f'<g id="{gid}">')

    def end(self):
        self.add("</g>")

    # ---- primitives -------------------------------------------------------------
    def text(self, x, y, s, *, size=F_BODY, weight="normal", color=INK, anchor="start",
             italic=False, family=FONT, spacing=None):
        """``y`` is the visual centre of a capital letter, not the baseline."""
        base = y + 0.36 * size * PT
        attrs = [f'x="{x:.2f}"', f'y="{base:.2f}"', f'font-size="{size * PT:.3f}"', f'fill="{color}"']
        if family != FONT:
            attrs.append(f'font-family="{family}"')
        if weight != "normal":
            attrs.append(f'font-weight="{weight}"')
        if anchor != "start":
            attrs.append(f'text-anchor="{anchor}"')
        if italic:
            attrs.append('font-style="italic"')
        if spacing is not None:
            attrs.append(f'letter-spacing="{spacing}"')
        self.add(f'<text {" ".join(attrs)}>{html.escape(s)}</text>')

    def line(self, pts, *, color=AXIS, width=LW_LINE, dash=None, cap="butt", opacity=None):
        d = "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts)
        extra = f' stroke-dasharray="{dash}"' if dash else ""
        extra += f' stroke-opacity="{opacity}"' if opacity is not None else ""
        self.add(f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{width:.3f}" '
                 f'stroke-linecap="{cap}" stroke-linejoin="round"{extra}/>')

    def head(self, tip, frm, *, color, length=1.25, width=1.0):
        """Filled arrowhead at ``tip`` pointing away from ``frm``."""
        dx, dy = tip[0] - frm[0], tip[1] - frm[1]
        n = math.hypot(dx, dy) or 1
        ux, uy = dx / n, dy / n
        bx, by = tip[0] - ux * length, tip[1] - uy * length
        p1 = (bx - uy * width / 2, by + ux * width / 2)
        p2 = (bx + uy * width / 2, by - ux * width / 2)
        self.add(f'<path d="M{tip[0]:.2f} {tip[1]:.2f} L{p1[0]:.2f} {p1[1]:.2f} '
                 f'L{p2[0]:.2f} {p2[1]:.2f}Z" fill="{color}"/>')

    def arrow(self, pts, *, color, width=LW_ARROW, dash=None, length=1.25, head_w=1.0):
        tip, frm = pts[-1], pts[-2]
        dx, dy = tip[0] - frm[0], tip[1] - frm[1]
        n = math.hypot(dx, dy) or 1
        short = (tip[0] - dx / n * length * 0.8, tip[1] - dy / n * length * 0.8)
        self.line(list(pts[:-1]) + [short], color=color, width=width, dash=dash)
        self.head(tip, frm, color=color, length=length, width=head_w)

    def rect(self, x, y, w, h, *, fill="none", stroke="none", width=LW_LINE, rx=0, dash=None,
             opacity=None):
        extra = f' rx="{rx}"' if rx else ""
        extra += f' stroke-dasharray="{dash}"' if dash else ""
        extra += f' fill-opacity="{opacity}"' if opacity is not None else ""
        sw = f' stroke-width="{width:.3f}"' if stroke != "none" else ""
        self.add(f'<rect x="{x:.2f}" y="{y:.2f}" width="{w:.2f}" height="{h:.2f}" fill="{fill}" '
                 f'stroke="{stroke}"{sw}{extra}/>')

    def circle(self, cx, cy, r, *, fill="none", stroke="none", width=LW_LINE):
        sw = f' stroke-width="{width:.3f}"' if stroke != "none" else ""
        self.add(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r:.2f}" fill="{fill}" stroke="{stroke}"{sw}/>')

    def gene(self, x0, x1, y, *, strand="+", h=1.1, fill=GENE_FILL, edge=GENE_EDGE, width=LW_GENE):
        """Figure 4 gene arrow: pentagon on the locus axis, ``h`` is the half-height."""
        hd = min(0.38 * (x1 - x0), 1.3)
        if strand == "+":
            pts = [(x0, y - h), (x1 - hd, y - h), (x1, y), (x1 - hd, y + h), (x0, y + h)]
        else:
            pts = [(x1, y - h), (x0 + hd, y - h), (x0, y), (x0 + hd, y + h), (x1, y + h)]
        d = "M" + " L".join(f"{px:.2f} {py:.2f}" for px, py in pts) + "Z"
        self.add(f'<path d="{d}" fill="{fill}" stroke="{edge}" stroke-width="{width:.3f}" '
                 f'stroke-linejoin="round"/>')

    def asset(self, name, x, y, width, *, rotate=0.0, pivot=None, gid=None):
        """Place an extracted drawing with its top-left at (x, y) mm, scaled to ``width`` mm."""
        src = (ASSETS / f"{name}.svg").read_text(encoding="utf-8")
        vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', src).group(1).split()]
        inner = src[src.index(">", src.index("<svg")) + 1: src.rindex("</svg>")].strip()
        s = width / vb[2]
        rot = ""
        if rotate:
            px, py = pivot if pivot else (vb[2] / 2, vb[3] / 2)
            rot = f" rotate({rotate} {px} {py})"
        self.add(f'<g id="{gid or name}" transform="translate({x:.3f} {y:.3f}) scale({s:.5f}){rot}">'
                 f"{inner}</g>")
        return s, vb[3] * s

    def save(self, path: Path):
        defs = (
            '<defs><radialGradient id="ion" cx="0.38" cy="0.34" r="0.7">'
            '<stop offset="0" stop-color="#FFE7AE"/><stop offset="0.45" stop-color="#F6A42C"/>'
            '<stop offset="1" stop-color="#DC5A1B"/></radialGradient></defs>'
        )
        body = "\n".join(self.out)
        path.write_text(
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}mm" height="{H}mm" '
            f'viewBox="0 0 {W} {H}" font-family="{FONT}">\n<title>Figure 1</title>\n{defs}\n'
            f'<rect width="{W}" height="{H}" fill="#FFFFFF"/>\n{body}\n</svg>\n',
            encoding="utf-8")


# ---- reusable glyphs -------------------------------------------------------------
def doc(c: Svg, x, y, w, h, tag, *, body="lines"):
    """File icon with a folded corner and a format tag."""
    f = 1.0
    c.add(f'<path d="M{x:.2f} {y:.2f} H{x + w - f:.2f} L{x + w:.2f} {y + f:.2f} V{y + h:.2f} '
          f'H{x:.2f}Z" fill="#FFFFFF" stroke="#8C8FA3" stroke-width="{0.4 * PT:.3f}" stroke-linejoin="round"/>')
    c.add(f'<path d="M{x + w - f:.2f} {y:.2f} V{y + f:.2f} H{x + w:.2f}" fill="none" stroke="#8C8FA3" '
          f'stroke-width="{0.4 * PT:.3f}" stroke-linejoin="round"/>')
    c.rect(x + 0.35, y + 0.35, w - f - 0.2, 2.0, fill="#ECE9F3")
    c.text(x + (w - f) / 2 + 0.2, y + 1.35, tag, size=F_TAG, weight="bold", color=TF_DARK, anchor="middle")
    if body == "lines":
        for i, frac in enumerate((0.78, 0.62, 0.7)):
            yy = y + 3.4 + i * 1.25
            c.line([(x + 0.9, yy), (x + 0.9 + (w - 1.8) * frac, yy)], color="#B7BAC8", width=0.35 * PT)
    elif body == "table":
        top, bot = y + 2.9, y + h - 0.8
        for i in range(4):
            yy = top + i * (bot - top) / 3
            c.line([(x + 0.7, yy), (x + w - 0.7, yy)], color="#B7BAC8", width=0.35 * PT)
        for frac in (0.38, 0.68):
            xx = x + 0.7 + (w - 1.4) * frac
            c.line([(xx, top), (xx, bot)], color="#B7BAC8", width=0.35 * PT)
    elif body == "genes":
        yy = y + h - 2.4
        c.line([(x + 0.6, yy), (x + w - 0.6, yy)], color=AXIS, width=0.35 * PT)
        c.gene(x + 0.8, x + 3.0, yy, h=0.55, width=0.3 * PT)
        c.gene(x + 3.4, x + 5.4, yy, strand="-", h=0.55, width=0.3 * PT)
        c.gene(x + 5.8, x + w - 0.8, yy, h=0.55, fill=TF_LIGHT, edge=TF_MID, width=0.3 * PT)
        c.line([(x + 0.9, y + 3.4), (x + w * 0.62, y + 3.4)], color="#B7BAC8", width=0.35 * PT)


def clade(c: Svg, cx, cy, w, h, *, node, edge="#B4B4BE", hilite=None, hilite_fill=None,
          r=0.33, hilite_r=0.55, gid="ssn_clade"):
    """MerR cluster 7 from the SSN view, rotated to its long axis and fitted into w x h mm."""
    data = json.loads((ASSETS / "merr_clade7.json").read_text(encoding="utf-8"))
    ids = list(data["nodes"])
    xs = [data["nodes"][i][0] for i in ids]
    ys = [data["nodes"][i][1] for i in ids]
    mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    ang = 0.5 * math.atan2(2 * sxy, sxx - syy)
    ca, sa = math.cos(-ang), math.sin(-ang)
    rot = {i: ((x - mx) * ca - (y - my) * sa, (x - mx) * sa + (y - my) * ca) for i, x, y in zip(ids, xs, ys)}
    rx = [p[0] for p in rot.values()]
    ry = [p[1] for p in rot.values()]
    s = min((w - 2 * r) / (max(rx) - min(rx)), (h - 2 * r) / (max(ry) - min(ry)))
    ox, oy = (max(rx) + min(rx)) / 2, (max(ry) + min(ry)) / 2
    pos = {i: (cx + (p[0] - ox) * s, cy + (p[1] - oy) * s) for i, p in rot.items()}
    c.group(gid)
    d = "".join(f"M{pos[a][0]:.2f} {pos[a][1]:.2f}L{pos[b][0]:.2f} {pos[b][1]:.2f}" for a, b in data["edges"])
    c.add(f'<path d="{d}" fill="none" stroke="{edge}" stroke-width="{0.12 * PT:.3f}" stroke-opacity="0.75"/>')
    special = {data["anchors"][k] for k in (hilite or []) if k in data["anchors"]}
    for i in ids:
        if i not in special:
            c.circle(*pos[i], r, fill=node, stroke="#4A4A55", width=0.12 * PT)
    for i in special:
        c.circle(*pos[i], hilite_r, fill=hilite_fill, stroke=INK, width=0.25 * PT)
    c.end()


def half_sites(c: Svg, x0, x1, y, *, color=OP, size=0.75):
    """Inverted-repeat cue: a pair of opposed arrows over a site."""
    mid = (x0 + x1) / 2
    c.arrow([(x0, y), (mid - 0.25, y)], color=color, width=0.45 * PT, length=size, head_w=size * 0.8)
    c.arrow([(x1, y), (mid + 0.25, y)], color=color, width=0.45 * PT, length=size, head_w=size * 0.8)


def logo(c: Svg, x0, base, col_w, columns):
    """Sequence-logo glyphs: ``columns`` is a list of [(letter, height_mm), ...] bottom-up."""
    adv = {"A": 0.722, "C": 0.722, "G": 0.778, "T": 0.611}
    f = 3.0
    for i, stack in enumerate(columns):
        y = base
        for letter, hgt in stack:
            if hgt < 0.05:
                continue
            hgt *= 2.1
            sy = hgt / (0.716 * f)
            sx = col_w * 0.9 / (adv[letter] * f)
            fill = OP_DARK if hgt > 4.4 else (OP if hgt > 2.0 else "#B5B9C2")
            c.add(f'<text transform="translate({x0 + (i + 0.5) * col_w:.3f} {y:.3f}) scale({sx:.3f} {sy:.3f})" '
                  f'font-size="{f}" font-weight="bold" text-anchor="middle" fill="{fill}">{letter}</text>')
            y -= hgt


def ion(c: Svg, cx, cy, r):
    c.add(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r:.2f}" fill="url(#ion)" stroke="{IND_DARK}" '
          f'stroke-width="{0.3 * PT:.3f}"/>')


