def export(svg: Path):
    """PDF and 600 dpi PNG through headless Chrome/Edge (text stays text), then an LZW TIFF."""
    exe = next((p for p in [shutil.which("chrome"), shutil.which("msedge"),
                            r"C:\Program Files\Google\Chrome\Application\chrome.exe",
                            r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"]
                if p and Path(p).exists()), None)
    if exe is None:
        print("No Chrome/Edge found; wrote SVG only.")
        return
    page = (f"<!doctype html><html><head><meta charset='utf-8'><style>@page{{size:{W}mm {H}mm;margin:0}}"
            f"html,body{{margin:0;padding:0;background:#fff;overflow:hidden}}svg{{display:block}}"
            f"</style></head><body>{svg.read_text(encoding='utf-8')}</body></html>")
    png = svg.with_suffix(".png")
    with tempfile.TemporaryDirectory() as tmp:
        wrap = Path(tmp) / "page.html"
        wrap.write_text(page, encoding="utf-8")
        common = [exe, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                  "--default-background-color=ffffffff", f"--user-data-dir={Path(tmp) / 'profile'}"]
        subprocess.run(common + [f"--print-to-pdf={svg.with_suffix('.pdf')}", "--no-pdf-header-footer",
                                 wrap.as_uri()], check=True, capture_output=True, timeout=120)
        # 96 css px per inch x 6.25 = 600 dpi.
        px_w, px_h = round(W / 25.4 * 96), round(H / 25.4 * 96)
        subprocess.run(common + ["--force-device-scale-factor=6.25", f"--window-size={px_w},{px_h}",
                                 f"--screenshot={png}", wrap.as_uri()],
                       check=True, capture_output=True, timeout=120)
    from PIL import Image
    with Image.open(png) as im:
        rgb = im.convert("RGB")
    rgb.save(png, dpi=(600, 600))
    rgb.save(svg.with_suffix(".tiff"), dpi=(600, 600), compression="tiff_lzw")


def main(stem: str = "fig1_pipeline", out_dir: Path = FIGDIR):
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"{stem}.svg"
    build(out)
    export(out)
    print(f"  wrote {out.relative_to(out_dir.parent)} [+ pdf|png|tiff]  ({W:.0f} x {H} mm)")
    return 0


